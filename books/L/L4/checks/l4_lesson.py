import sympy as sp

M = sp.Matrix


def ok(label, condition):
    print(f"PASS {label}" if bool(condition) else f"FAIL {label}")


x, y, z = sp.symbols('x y z')

# 第 1 节开头的 2x2 方程组与列向量说法
s = sp.solve([2*x - y - 1, x + y - 5], [x, y], dict=True)[0]
ok("引例2x2", s == {x: 2, y: 3} and 2*M([2, 1]) + 3*M([-1, 1]) == M([1, 5]))

# 例 1 禾问题
sol = sp.solve([3*x+2*y+z-39, 2*x+3*y+z-34, x+2*y+3*z-26], [x, y, z], dict=True)[0]
ok("例1", sol == {x: sp.Rational(37, 4), y: sp.Rational(17, 4), z: sp.Rational(11, 4)})
aug = M([[1, 2, 3, 26], [2, 3, 1, 34], [3, 2, 1, 39]])
aug[1, :] -= 2*aug[0, :]; aug[2, :] -= 3*aug[0, :]; aug[2, :] -= 4*aug[1, :]
ok("例1消元", aug.row(2) == M([[0, 0, 12, 33]]))
sol1b = sp.solve([x+y+z-6, 2*x-y+z-3, x+2*y-z-2], [x, y, z], dict=True)[0]
ok("例1小题", sol1b == {x: 1, y: 2, z: 3})

# 例 2 老朋友⑤⑥
A5 = M([[1, 2, 1], [2, 4, 3], [3, 6, 4]])
A6 = M([[2, 1, 0], [1, 2, 1], [0, 1, 2]])
ok("例2-⑤", A5.rref() == (M([[1, 2, 0], [0, 0, 1], [0, 0, 0]]), (0, 2)))
B = A6.copy(); B[1, :] = 2*B[1, :] - B[0, :]; B[2, :] = 3*B[2, :] - B[1, :]
ok("例2-⑥阶梯形", B == M([[2, 1, 0], [0, 3, 2], [0, 0, 4]]) and A6.rref()[0] == sp.eye(3))
r2b, p2b = M([[0, 2, 4, 2], [1, 1, 3, 2], [2, 4, 10, 6]]).rref()
ok("例2小题", r2b == M([[1, 0, 1, 1], [0, 1, 2, 1], [0, 0, 0, 0]]) and p2b == (0, 1))

# 例 3
A3 = M([[1, 2, 0, 1], [2, 4, 1, 4], [1, 2, 1, 3]]); b3 = M([3, 8, 5])
ok("例3", A3*M([3, 0, 2, 0]) == b3 and A3*M([-2, 1, 0, 0]) == M.zeros(3, 1)
   and A3*M([-1, 0, -2, 1]) == M.zeros(3, 1) and A3.rank() == 2)
Ab = M([[1, -1, 1], [2, -2, 3]])
ok("例3小题", Ab*M([-1, 0, 2]) == M([1, 4]) and Ab*M([1, 1, 0]) == M.zeros(2, 1))

# 例 4 ⑤x=b
b1, b2, b3s = sp.symbols('b1 b2 b3')
G = A5.row_join(M([b1, b2, b3s]))
G[1, :] -= 2*G[0, :]; G[2, :] -= 3*G[0, :]; G[2, :] -= G[1, :]
ok("例4条件", sp.simplify(G[2, 3] - (b3s - b1 - b2)) == 0 and G[2, :3] == M([[0, 0, 0]]))
ok("例4通解", A5*M([3, 0, -1]) == M([2, 3, 5]) and A5*M([-2, 1, 0]) == M.zeros(3, 1))
ok("例4像外点", A5.row_join(M([1, 1, 1])).rank() > A5.rank())

# 例 5 参数讨论
a, b = sp.symbols('a b')
C = M([[1, 1, 1, 1], [1, 2, 3, 3], [1, 3, a, b]])
C[1, :] -= C[0, :]; C[2, :] -= C[0, :]; C[2, :] -= 2*C[1, :]
ok("例5末行", C.row(2) == M([[0, 0, a-5, b-5]]))
A5b = M([[1, 1, 1], [1, 2, 3], [1, 3, 5]])
ok("例5无穷解", A5b*M([-1, 2, 0]) == M([1, 3, 5]) and A5b*M([1, -2, 1]) == M.zeros(3, 1))
ok("齐次小题", M([[1, 1, 1], [1, -1, 2]])*M([-3, 1, 2]) == M.zeros(2, 1))

# 第 4 节
ok("②左右乘", M([[1, 1], [0, 1]])*M([[1, 2], [3, 4]]) == M([[4, 6], [3, 4]])
   and M([[1, 2], [3, 4]])*M([[1, 1], [0, 1]]) == M([[1, 3], [3, 7]]))
E21 = M([[1, 0, 0], [-2, 1, 0], [0, 0, 1]]); E31 = M([[1, 0, 0], [0, 1, 0], [-3, 0, 1]])
E32 = M([[1, 0, 0], [0, 1, 0], [0, -1, 1]])
P = E32*E31*E21
ok("⑤消元矩阵", P == M([[1, 0, 0], [-2, 1, 0], [-1, -1, 1]]) and P*A5 == M([[1, 2, 1], [0, 0, 1], [0, 0, 0]]))
A = M([[1, 2], [3, 4]])
ok("例6", M([[1, 0], [-3, 1]])*A == M([[1, 2], [0, -2]]) and M([[1, 0], [3, 1]])*M([[1, 2], [0, -2]]) == A)
ok("例6小题", M([[1, 0, 0], [0, 0, 1], [0, 1, 0]])*M([[1, 0, 0], [0, 1, 0], [-2, 0, 1]]) == M([[1, 0, 0], [-2, 0, 1], [0, 1, 0]]))
Q = M([[0, 1, 0], [1, 0, 0], [0, 0, 1]])*M([[1, 0, 0], [0, 1, 2], [0, 0, 1]])
ok("例7", Q == M([[0, 1, 2], [1, 0, 0], [0, 0, 1]]))
