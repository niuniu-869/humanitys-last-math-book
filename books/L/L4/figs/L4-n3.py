arrow(ax,(0,0),(1,0),color=C.INK,text='$\\boldsymbol{e}_2\\to(1,0)$',offset=(3,-15),lw=1.3)
ax.fill([.5,.9,.5],[.1,.1,.32],facecolor='none',edgecolor=C.INK,ls='--',lw=1.1)
