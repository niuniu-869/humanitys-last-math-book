import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, axs = new_fig(16, 7, ncols=2)
ax, bx = axs
x = np.linspace(-1, 5, 400)
ax.plot(x, 2*x-1, ls='-', color=C.BLUE)
ax.plot(x, 5-x, ls='--', color=C.RED)
ax.set_xlim(-1,5); ax.set_ylim(-1,6); ax.set_aspect('equal', adjustable='box')
ax.set_title('方程组：两条直线')
ax.grid(True, color=C.LIGHT, lw=0.6)
ax.set_xlabel('x'); ax.set_ylabel('y')
label(ax, '$2x-y=1$', (3.35, 5.7))
label(ax, '$x+y=5$', (3.6, 1.25))
dot(ax, (2,3), '$(2,3)$', offset=(6,7), color=C.INK)

bx.set_xlim(-2,5); bx.set_ylim(-1,6); bx.set_aspect('equal', adjustable='box')
bx.set_title('列向量：两列拼出 $\\boldsymbol{b}$')
bx.grid(True, color=C.LIGHT, lw=0.6)
bx.set_xlabel('x'); bx.set_ylabel('y')
arrow(bx, (0,0), (2,1), color=C.BLUE, lw=1.2, text='第一列 $(2,1)$', offset=(-4,-18))
arrow(bx, (0,0), (-1,1), color=C.RED, lw=1.2, text='第二列 $(-1,1)$', offset=(-45,3))
bx.plot([0,4,1], [0,2,5], color=C.INK, ls='-', lw=2.6)
label(bx, '$2\\boldsymbol{a}_1$', (4,2), offset=(4,5))
label(bx, '$+3\\boldsymbol{a}_2$', (1,5), offset=(6,-14))
bx.annotate('', xy=(1,5), xytext=(0,0), arrowprops=dict(arrowstyle='-|>', color=C.TEAL, lw=1.5, linestyle='--', mutation_scale=11))
label(bx, '$\\boldsymbol{b}=(1,5)$', (1,5), offset=(6,3))
dot(bx, (1,5), color=C.INK, size=26)
fig.tight_layout(w_pad=2.2)
save(fig, "L4-n1")
