"""核对 lesson.md（v2 重写）中老朋友、例 1--10 与随堂小题的数值与结论。"""
import sympy as sp

M = sp.Matrix
def ok(tag, condition):
    print(f"PASS {tag}" if bool(condition) else f"FAIL {tag}")

F1 = M([[2, 1], [1, 2]]); S = M([[1, 1], [0, 1]]); R = M([[0, -1], [1, 0]])
H1 = sp.Rational(1, 2) * M([[1, 1], [1, 1]]); H2 = sp.Rational(1, 2) * M([[1, -1], [-1, 1]])

# 第 1 节礼盒与例 1、小题
ok("礼盒", M([[1, 3], [2, 1]]) * M([2, 1]) == M([5, 5]))
ok("例1", M([[1, 2, 0], [-1, 1, 3]]) * M([3, 1, -1]) == M([5, -5]))
ok("例1小题", M([[2, 0, 1], [1, -1, 0]]) * M([1, 2, -1]) == M([1, -1]))

# 第 2 节老朋友
ok("网格点", F1 * M([2, 1]) == M([5, 4]))
ok("老朋友1方向", F1 * M([1, 1]) == M([3, 3]) and F1 * M([-1, 1]) == M([-1, 1]))
ok("老朋友2坐标", S * M([3, 2]) == M([5, 2]))
ok("老朋友4", H1 * M([1, 0]) == M([sp.Rational(1, 2)] * 2) and H1 * M([1, 1]) == M([1, 1]) and H1 * M([-1, 1]) == M([0, 0]))
a = M([1, 2]); H = (a * a.T) / (a.T * a)[0]
ok("投影小题", H == sp.Rational(1, 5) * M([[1, 2], [2, 4]]) and H * a == a and H * M([2, -1]) == M([0, 0]))

# 例 2
th = sp.symbols('theta')
Rt = M([[sp.cos(th), -sp.sin(th)], [sp.sin(th), sp.cos(th)]])
ok("例2", Rt.subs(th, sp.pi / 2) == R and R * M([2, 1]) == M([-1, 2]) and M([2, 1]).dot(M([-1, 2])) == 0)

# 例 3、小题、例 4
ok("例3", M([[1, 2, 0], [-1, 0, 3]]) * M([1, 0, 0]) == M([1, -1]))
ok("例3小题", M([[0, 1], [1, -1], [2, 0]]) * M([3, 5]) == M([5, -2, 6]))
T = M([[2, 1], [1, 2]])
ok("例4", T * M([1, 1]) == M([3, 3]) and T * M([-1, 1]) == M([-1, 1]) and T * M([2, 5]) == M([9, 12]))

# 第 4 节
ok("SR", S * R == M([[1, -1], [1, 0]]))
ok("RS", R * S == M([[0, -1], [1, 1]]) and S * R != R * S)
A = M([[1, 2], [0, 1], [-1, 3]]); B = M([[2, 0, 1], [1, -1, 0]])
ok("例5", A * B == M([[4, -2, 1], [1, -1, 0], [1, -3, -1]]) and B * A == M([[1, 7], [1, 1]]))
W = M([[0, 1], [1, 0]]); A2 = M([[1, 2], [3, 4]])
ok("例5小题", A2 * W == M([[2, 1], [4, 3]]) and W * A2 == M([[3, 4], [1, 2]]))
a_, b_, c_, d_ = sp.symbols('a b c d'); X = M([[a_, b_], [c_, d_]])
sol = sp.solve(list(S * X - X * S), [c_, d_], dict=True)
ok("与剪切可交换", sol == [{c_: 0, d_: a_}])
ok("零因子", H1 * H2 == sp.zeros(2, 2))
W1 = M([[1, 0, -1], [2, 1, 0]]); W2 = M([[1, 1], [1, -1]]); x = M([1, 2, 3])
ok("例6", W1 * x == M([-2, 4]) and W2 * W1 == M([[3, 1, -1], [-1, -1, -1]]) and W2 * (W1 * x) == M([2, -6]))

# 第 5 节
ok("幂", R ** 4 == sp.eye(2) and H1 ** 2 == H1 and S ** 7 == M([[1, 7], [0, 1]]))
P = M([[1, 0], [0, 0]]); Q = M([[0, 1], [0, 0]])
ok("二项式反例", (P + Q) ** 2 == P + Q and P ** 2 + 2 * P * Q + Q ** 2 == P + 2 * Q)
n = sp.symbols('n', integer=True, positive=True)
A8 = M([[2, 1, 0], [0, 2, 1], [0, 0, 2]])
An = M([[2**n, n * 2**(n - 1), n * (n - 1) * 2**(n - 3)], [0, 2**n, n * 2**(n - 1)], [0, 0, 2**n]])
ok("例7", all(sp.simplify(An.subs(n, k) - A8 ** k) == sp.zeros(3, 3) for k in range(2, 9)))
B8 = M([[-1, 2], [0, -1]])
ok("例7小题", all(B8 ** k == M([[(-1)**k, 2 * k * (-1)**(k - 1)], [0, (-1)**k]]) for k in range(1, 9)))
A9 = M([[1, -1], [2, 4]])
ok("例8", A9 ** 2 - 5 * A9 + 6 * sp.eye(2) == sp.zeros(2, 2) and A9 ** 3 == 19 * A9 - 30 * sp.eye(2) == M([[-11, -19], [38, 46]]))

# 第 6 节
ok("转置次序", (S * R).T == R.T * S.T == M([[1, 1], [-1, 0]]) and S.T * R.T == M([[0, 1], [-1, 1]]))
Ar = sp.Matrix(2, 3, sp.symbols('p0:6')); Br = sp.Matrix(3, 2, sp.symbols('q0:6'))
ok("例9", (Ar * Br).T == Br.T * Ar.T and (Ar.T * Ar).T == Ar.T * Ar)
A10 = M([[1, 4], [2, 3]]); K1 = (A10 + A10.T) / 2; K2 = (A10 - A10.T) / 2
ok("例9小题", K1 == M([[1, 3], [3, 3]]) and K2 == M([[0, 1], [-1, 0]]) and K1 + K2 == A10)
U1 = M([[1, 2, 3], [0, 4, 5], [0, 0, 6]]); U2 = M([[7, 8, 9], [0, 1, 2], [0, 0, 3]])
Up = U1 * U2
ok("三角乘积", all(Up[i, j] == 0 for i in range(3) for j in range(i)) and [Up[i, i] for i in range(3)] == [7, 4, 18])

# 第 7 节
Mb = M([[1, 1, 0, 0], [0, 1, 0, 0], [0, 0, 2, 0], [0, 0, 1, 2]])
ok("分块幂", all(Mb ** k == M([[1, k, 0, 0], [0, 1, 0, 0], [0, 0, 2**k, 0], [0, 0, k * 2**(k - 1), 2**k]]) for k in range(1, 8)))
al = M([1, 2, 3]); be = M([1, -1, 1]); A11 = al * be.T
ok("例10", A11 == M([[1, -1, 1], [2, -2, 2], [3, -3, 3]]) and (be.T * al)[0] == 2 and all(A11 ** k == 2**(k - 1) * A11 for k in range(1, 8)))
A12 = M([[1, 2], [3, 6]])
ok("例10小题", all(A12 ** k == 7**(k - 1) * A12 for k in range(1, 8)))
Ao = M([[1, 2], [3, 4]]); Bo = M([[5, 6], [7, 8]])
ok("外积展开", Ao * Bo == Ao[:, 0] * Bo[0, :] + Ao[:, 1] * Bo[1, :])
