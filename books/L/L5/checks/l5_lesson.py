import sympy as sp

M = sp.Matrix
R = sp.Rational
E2 = sp.eye(2)
E3 = sp.eye(3)


def check(name, cond):
    print(f"PASS {name}" if cond else f"FAIL {name}")


# 第 1 节：③、②的撤销
F3 = M([[0, -1], [1, 0]]); F2 = M([[1, 1], [0, 1]])
check("③撤销", F3 * M([[0, 1], [-1, 0]]) == E2 and M([[0, 1], [-1, 0]]) * F3 == E2 and F3.inv() == F3.T)
check("②撤销", F2.inv() == M([[1, -1], [0, 1]]))

# 非方阵：AB=E2，BA≠E3，且 Ax=0 有非零解
A = M([[1, 0, 0], [0, 1, 0]]); B = M([[1, 0], [0, 1], [0, 0]])
check("非方阵", A * B == E2 and B * A != E3 and A * M([0, 0, 1]) == M.zeros(2, 1))

# 二阶公式由来：A x = e1 的解
a, b, c, d = sp.symbols('a b c d')
G = M([[a, b], [c, d]])
s1 = G.LUsolve(M([1, 0])).applyfunc(sp.simplify)
check("二阶公式第1列", sp.simplify(s1 - M([d, -c]) / (a*d - b*c)) == M.zeros(2, 1))
check("AA*", sp.simplify(G * M([[d, -b], [-c, a]]) - (a*d - b*c) * E2) == M.zeros(2, 2))
F4 = M([[R(1, 2), R(1, 2)], [R(1, 2), R(1, 2)]])
check("④不可逆", F4.det() == 0 and F4 * M([1, 0]) == F4 * M([0, 1]) == M([R(1, 2), R(1, 2)])
      and F4 * M([-1, 1]) == M.zeros(2, 1))

# 例 1 ①
F1 = M([[2, 1], [1, 2]])
check("例1", F1.inv() == R(1, 3) * M([[2, -1], [-1, 2]]) and F1.inv() * M([3, 0]) == M([2, -1]))
check("例1小题", M([[2, 1], [5, 3]]).inv() == M([[3, -1], [-5, 2]]))

# 例 2
Bm = M([[1, 0], [2, 1]])
check("例2", (F2 * Bm).inv() == M([[1, -1], [-2, 3]]) and F2.inv() * Bm.inv() == M([[3, -1], [-2, 1]]))
# 运算律图：(②③)^{-1} = ③^{-1}②^{-1}
check("图L5-n4", F2 * F3 == M([[1, -1], [1, 0]]) and (F2 * F3).inv() == F3.inv() * F2.inv() == M([[0, 1], [-1, 1]]))

# 第 2 节：(1 2;3 4) 写成初等矩阵之积
Ae = M([[1, 2], [3, 4]])
P = M([[1, -2], [0, 1]]) * M([[1, 0], [0, R(-1, 2)]]) * M([[1, 0], [-3, 1]])
check("初等矩阵分解", P * Ae == E2 and M([[1, 0], [3, 1]]) * M([[1, 0], [0, -2]]) * M([[1, 2], [0, 1]]) == Ae)

# 例 3
A3 = M([[1, 2, 1], [2, 3, 1], [1, 1, 0]])
check("例3", A3.rank() == 2 and A3 * M([1, -1, 1]) == M.zeros(3, 1))
check("例3小题", M([[1, 0, 2], [0, 1, 1], [1, 1, 2]]).rank() == 3)

# 例 4
N = M([[0, 1, 2], [0, 0, 3], [0, 0, 0]])
check("例4", N**3 == M.zeros(3, 3) and (E3 - N).inv() == E3 + N + N**2 == M([[1, 1, 5], [0, 1, 3], [0, 0, 1]]))

# 例 5 ⑥
F6 = M([[2, 1, 0], [1, 2, 1], [0, 1, 2]])
aug = F6.row_join(E3)
aug.row_swap(0, 1); aug[1, :] -= 2 * aug[0, :]; aug.row_swap(1, 2); aug[2, :] += 3 * aug[1, :]
check("例5阶梯形", aug == M([[1, 2, 1, 0, 1, 0], [0, 1, 2, 0, 0, 1], [0, 0, 4, 1, -2, 3]]))
check("例5", F6.inv() == R(1, 4) * M([[3, -2, 1], [-2, 4, -2], [1, -2, 3]]) and F6.inv() == F6.inv().T)
check("例5小题", M([[1, 1, 1], [0, 1, 1], [0, 0, 1]]).inv() == M([[1, -1, 0], [0, 1, -1], [0, 0, 1]]))

# 分块
Bd = M([[3, 0, 0], [0, 2, 1], [0, 5, 3]])
check("分块对角", Bd.inv() == M([[R(1, 3), 0, 0], [0, 3, -1], [0, -5, 2]]))
A1 = M([[2, 1], [5, 3]]); A2 = M([[1, 1], [0, 1]]); Cb = M([[1, 2], [3, 4]])
Mb = sp.BlockMatrix([[A1, Cb], [sp.zeros(2), A2]]).as_explicit()
Mi = sp.BlockMatrix([[A1.inv(), -A1.inv() * Cb * A2.inv()], [sp.zeros(2), A2.inv()]]).as_explicit()
check("分块上三角公式", Mb * Mi == sp.eye(4))

# 第 4 节：由两个像求 X
X = M([[3, 1], [1, -1]]) * M([[1, 1], [1, -1]]).inv()
check("求变换矩阵", X == M([[2, 1], [0, 1]]) and X * M([1, 1]) == M([3, 1]) and X * M([1, -1]) == M([1, -1]))

# 例 6
Bb = M([[1, 0, 2], [2, 1, 1]])
check("例6", A1.inv() * Bb == M([[1, -1, 5], [-1, 2, -8]]))
check("例6小题", M([[1, 1], [0, 1]]) * A1.inv() == M([[-2, 1], [-5, 2]]))

# 例 7：用满足 A^2-A-2E=O 的具体矩阵核对公式
Ad = M([[2, 0], [0, -1]])
check("例7", Ad**2 - Ad - 2 * E2 == M.zeros(2, 2) and Ad.inv() == R(1, 2) * (Ad - E2)
      and (Ad + 2 * E2).inv() == R(-1, 4) * (Ad - 3 * E2))
x = sp.symbols('x')
check("例7除法", sp.expand((x + 2) * (x - 3) + 4 - (x**2 - x - 2)) == 0)

# 例 8 投入产出
L = M([[R(2, 10), R(4, 10)], [R(4, 10), R(3, 10)]])
Li = (E2 - L).inv()
check("例8", Li == M([[R(7, 4), 1], [1, 2]]) and Li * M([100, 200]) == M([375, 500]))
check("例8小题", Li * M([200, 100]) == M([450, 400]))
S = M([0, 1]); t = M([0, 1]); sums = []
for k in range(4):
    sums.append(S)
    t = L * t
    S = S + t
check("逐轮累加", sums == [M([0, 1]), M([R(4, 10), R(13, 10)]), M([R(6, 10), R(155, 100)]), M([R(74, 100), R(1705, 1000)])])
