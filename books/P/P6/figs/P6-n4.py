import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(14, 12)
t = np.linspace(0, 2*np.pi, 721)
for c in [1, 3, 6]:
    u, v = np.sqrt(2*c)*np.cos(t), np.sqrt(2*c/3)*np.sin(t)
    x, y = (u-v)/np.sqrt(2), (u+v)/np.sqrt(2)
    assert np.allclose(x*x-x*y+y*y, c)
    ax.plot(x, y, color=C.INK, ls='-')
ax.plot([-3.1, 3.1], [-3.1, 3.1], color=C.GRAY, ls='-.', lw=0.9)
ax.plot([-2.8, 2.8], [2.8, -2.8], color=C.GRAY, ls='-.', lw=0.9)
ax.plot([-4, 4], [-2, 2], color=C.INK, ls=':')
ax.axvline(2, color=C.INK, ls='--', lw=1)
sd = np.sqrt(1.5)
ax.plot([2, 2], [1-sd, 1+sd], color=C.INK, lw=4, solid_capstyle='butt')
ax.plot(2, 1, 'o', mfc=C.PAPER, mec=C.INK, ms=7, zorder=5)
label(ax, '$(2,1)$', (2.8, 0.55))
label(ax, '方差 3', (2.65, 3.15))
label(ax, '方差 1', (-2.6, 2.6), (-4, 10), ha='center')
label(ax, r'条件中心 $y=x/2$', (-3.7, -3.5))
label(ax, '切口：中心 1，方差 1.5', (-3.8, 3.6), ha='left', fontsize=9)
ax.set(xlim=(-4, 4), ylim=(-4, 4), aspect='equal', xlabel='$x$', ylabel='$y$')
ax.set_xticks([-4, -2, 0, 2, 4])
ax.set_yticks([-4, -2, 0, 2, 4])
ax.axhline(0, color=C.LIGHT, lw=0.8, zorder=0)
ax.axvline(0, color=C.LIGHT, lw=0.8, zorder=0)
save(fig, 'P6-n4')
