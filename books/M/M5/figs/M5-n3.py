import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

O = np.zeros(2)
P = np.array([2., 3.])
w = np.array([np.cos(np.pi / 6), np.sin(np.pi / 6)])
Q = (P @ w) * w
normal = (P - Q) / np.linalg.norm(P - Q)
assert np.isclose((P - Q) @ w, 0)
assert np.isclose(P @ P, Q @ Q + (P - Q) @ (P - Q))
fig, ax = new_fig(12, 10)
ax.plot(*np.outer([-0.4, 4.35], w).T, color=C.GRAY, lw=1, ls='-')
ax.plot(*np.array([O, P]).T, color=C.INK, ls='-', lw=1.6)
ax.plot(*np.array([O, Q]).T, color=C.INK, ls='-', lw=3)
ax.plot(*np.array([P, Q]).T, color=C.INK, ls='--', lw=1.5)
corner = np.array([Q - .17 * w, Q - .17 * w + .17 * normal, Q + .17 * normal])
ax.plot(*corner.T, color=C.INK, lw=1)
for point, name, offset in [(O, '$O$', (-4, -20)), (P, '$P$', (0, 10)), (Q, '$Q$', (6, -13))]:
    dot(ax, point, name, offset=offset, size=20)
label(ax, r'$\Vert x_c\Vert$', P / 2, offset=(-28, 4))
label(ax, r'$w^{\mathsf{T}}x_c$', Q / 2, offset=(10, -22))
label(ax, '重建误差', (P + Q) / 2, offset=(13, 4), fontsize=9)
label(ax, '$w$', 4.3 * w, offset=(0, 8))
ax.set(xlim=(-.5, 4.3), ylim=(-.5, 3.65), xlabel='$x$', ylabel='$y$')
ax.set_aspect('equal')
ax.set_xticks([0, 1, 2, 3, 4])
ax.set_yticks([0, 1, 2, 3])
fig.tight_layout()
save(fig, "M5-n3")
