import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(14, 8)
x = np.linspace(-4, 5, 900)
phi = lambda t: np.exp(-t**2 / 2) / np.sqrt(2 * np.pi)
c1 = 0.4 * phi(x + 1)
c2 = 0.6 * phi(x - 2)
p = c1 + c2
v1, v2 = 0.4 * phi(1), 0.6 * phi(2)
assert np.isclose(v1, 0.0968, atol=5e-5)
assert np.isclose(v2, 0.0324, atol=5e-5)
assert np.isclose(v1 + v2, 0.1292, atol=5e-5)
ax.plot(x, c1, ls='--', color=C.RED, label='成分 1，权重 0.4')
ax.plot(x, c2, ls='-.', color=C.TEAL, label='成分 2，权重 0.6')
ax.plot(x, p, ls='-', color=C.INK, lw=2.2)
ax.axvline(0, ls=':', color=C.GRAY, lw=1.2)
dot(ax, (0, v1), color=C.RED, size=28)
dot(ax, (0, v2), color=C.TEAL, size=28)
label(ax, '成分 1', (-1.0, 0.4*phi(0)), offset=(-45, 3), color=C.RED)
label(ax, '成分 2', (2.0, 0.6*phi(0)), offset=(30, -22), color=C.TEAL)
label(ax, '$p(x)$', (3.35, float(p[np.searchsorted(x, 3.35)])), offset=(6, 5))
label(ax, '后验 0.749 / 0.251', (0, v1), offset=(10, 3), ha='left')
label(ax, '$x=0$', (0, 0), offset=(5, -16), ha='left', color=C.GRAY)
ax.set(xlim=(-4, 5), ylim=(0, 0.29), xlabel='$x$', ylabel='密度')
ax.legend(loc='upper left')
save(fig, 'M16-n1')
