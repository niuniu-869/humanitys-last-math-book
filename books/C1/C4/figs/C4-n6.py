import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(10, 9)
xlim = (-1.0, 4.0); ylim = (-1.0, 4.0)
x_exp = np.linspace(xlim[0], xlim[1], 900)
x_log = np.linspace(0.08, xlim[1], 900)
ax.plot(x_exp, np.exp(x_exp), color=C.INK, lw=2.0, ls="-")
ax.plot(x_log, np.log(x_log), color=C.INK, lw=2.0, ls="--")
xx = np.linspace(-1, 4, 600)
ax.plot(xx, xx, color=C.GRAY, lw=1.0, ls=":")

ln2 = np.log(2.0)
T1 = (ln2, 2.0); T2 = (2.0, ln2)
dot(ax, T1, color=C.INK, size=28); dot(ax, T2, color=C.INK, size=28)
label(ax, r"$(\ln 2,2)$", T1, offset=(-58, 7))
label(ax, r"$(2,\ln 2)$", T2, offset=(5, -18))

xt = np.array(xlim)
ax.plot(xt, 2 + 2 * (xt - ln2), color=C.INK, lw=1.1, ls="-")
xl = np.array(xlim)
ax.plot(xl, ln2 + 0.5 * (xl - 2), color=C.INK, lw=1.1, ls="-")
assert np.isclose(np.exp(ln2), 2)
label(ax, "斜率 2", (1.9, 3.65), offset=(0, 0))
label(ax, r"斜率 $\frac{1}{2}$", (2.9, 1.7), offset=(0, 0))
label(ax, "$y=e^x$", (0.12, 3.35), offset=(0, 0))
label(ax, "$y=\\ln x$", (3.0, 0.7), offset=(0, 0))
label(ax, "$y=x$", (2.65, 2.95), offset=(0, 0))
ax.set_xlim(*xlim); ax.set_ylim(*ylim); ax.set_aspect("equal", adjustable="box")
ax.set_xlabel("$x$"); ax.set_ylabel("$y$")
ax.set_xticks([-1, 0, 1, 2, 3, 4]); ax.set_yticks([-1, 0, 1, 2, 3, 4])
save(fig, "C4-n6")
