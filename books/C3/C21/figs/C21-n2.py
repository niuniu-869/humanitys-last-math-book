theta = np.linspace(0, 2*np.pi, 800)
ax.plot(np.cos(theta), np.sin(theta), color=C.INK, ls="-", lw=1.4)
x = np.linspace(-.5, .5, 200)
ax.plot(x, np.sqrt(1-x*x), color=C.INK, lw=3, ls="-")
