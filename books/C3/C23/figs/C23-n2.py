import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from _h3 import *
V = View(-60, 26)
fig, ax = setup(12, 9.5)
P = np.array([0, 0, 2.0])
def sph(th, ph): return np.stack([2*np.sin(th)*np.cos(ph), 2*np.sin(th)*np.sin(ph), 2*np.cos(th)*np.ones_like(ph)], -1)
ph = np.linspace(0, 2*np.pi, 200)
for th in (0.35, 0.7, 1.05):
    line(ax, V, sph(th, ph), color="#888888", lw=0.7, ls=":")
th = np.linspace(0, 1.15, 40)
for p in np.arange(0, 2*np.pi, np.pi/6):
    line(ax, V, sph(th, p*np.ones_like(th)), color="#888888", lw=0.7, ls=":")
poly(ax, V, [[-1.5, -1.5, 2], [1.5, -1.5, 2], [1.5, 1.5, 2], [-1.5, 1.5, 2]], alpha=0.5, z=2)
s = np.linspace(-0.6, 0.6, 100)
line(ax, V, np.stack([2*np.sin(s), 0*s, 2*np.cos(s)], -1), lw=1.8)
line(ax, V, np.stack([0*s, 2*np.sin(s), 2*np.cos(s)], -1), lw=1.8, ls="--")
arrow3(ax, V, P, [1.3, 0, 0])
arrow3(ax, V, P, [0, 1.3, 0], ls="--")
arrow3(ax, V, P, [0, 0, 1.3], lw=1.8, ls=":")
dot3(ax, V, P, 40)
text3(ax, V, P+[1.3, 0, 0], r"$\boldsymbol{T}_1$", off=(4, -14), fontsize=14)
text3(ax, V, P+[0, 1.3, 0], r"$\boldsymbol{T}_2$", off=(4, 3), fontsize=14)
text3(ax, V, P+[0, 0, 1.3], r"$\nabla F(P)$", off=(6, 0), fontsize=13)
text3(ax, V, P, "$P$", off=(-16, -8), fontsize=13)
text3(ax, V, [-1.5, -1.5, 2], "切平面", off=(-10, -14), fontsize=11)
save(fig, "C23-n2")
