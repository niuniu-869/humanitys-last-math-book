import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(15, 9)
ax.set_aspect('equal'); ax.axis('off')
a, b = np.array([4., 0.]), np.array([2.5, 2.])
theta = np.arctan2(b[1], b[0])
arrow(ax, [0, 0], a, color=C.INK, lw=2, text=r'$\boldsymbol{a}$', offset=(5, -5))
arrow(ax, [0, 0], b, color=C.INK, lw=2, text=r'$\boldsymbol{b}$', offset=(-10, 9))
arrow(ax, b, a-b, color=C.INK, lw=1.3)
label(ax, r'$\boldsymbol{a}-\boldsymbol{b}$', (3.25, 1), (9, 2))
ax.plot([2.5, 2.5], [0, 2], ls=':', color=C.GRAY)
ax.plot([0, 2.5], [0, 0], lw=4, color=C.INK, solid_capstyle='butt')
ax.plot([2.33, 2.33, 2.5], [0, .17, .17], color=C.GRAY, lw=1)
t = np.linspace(0, theta, 60)
ax.plot(.65*np.cos(t), .65*np.sin(t), color=C.INK, lw=1)
label(ax, r'$\theta$', (.72, .27), (0, 0))
dot(ax, (0, 0), '$O$', offset=(-12, -14))
label(ax, r'投影长 $\Vert\boldsymbol{b}\Vert\cos\theta$', (1.25, 0), (0, -25), ha='center')
ax.set_xlim(-.35, 6.7); ax.set_ylim(-2.2, 2.65)
inset = ax.inset_axes([.65, .06, .34, .40])
inset.set_aspect('equal'); inset.axis('off')
bp = np.array([-1.5, 2.])
arrow(inset, [0, 0], [1.3, 0], color=C.INK, text=r'$\boldsymbol{a}$', offset=(2, -3))
arrow(inset, [0, 0], bp, color=C.INK, text=r"$\boldsymbol{b}'$", offset=(-4, 6))
inset.plot([-1.5, 0], [0, 0], lw=3, color=C.INK)
inset.plot([-1.5, -1.5], [0, 2], ls=':', color=C.GRAY)
label(inset, '$O$', (0, 0), (4, 7))
label(inset, '钝角时投影为负', (-.3, -.75), (0, 0), ha='center', fontsize=9)
inset.set_xlim(-2.2, 1.8); inset.set_ylim(-1, 2.6)
assert np.isclose(np.linalg.norm(b)*np.cos(theta), 2.5)
assert np.isclose(bp @ (a/np.linalg.norm(a)), -1.5)
save(fig, 'C19-n2')
