import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(13, 9)
ax.set_aspect('equal'); ax.axis('off')
phi = np.deg2rad(35)
s = np.array([np.cos(phi), np.sin(phi)])
ax.fill_between([-1.6, 4.3], -.1, .1, color=C.LIGHT, alpha=.5)
ax.plot([-1.6, 4.3], [0, 0], color=C.GRAY, lw=.7)
ax.plot(*np.array([-1.5*s, 4.5*s]).T, color=C.GRAY, lw=1.1)
ax.plot([0, 3.7], [0, 0], color=C.INK, ls='--', lw=1.7)
arrow(ax, [0, 0], 3.5*s, color=C.INK, text=r'$\boldsymbol{s}$', offset=(-4, 10), lw=2.3)
arrow(ax, [0, 0], [0, 2.8], color=C.INK, text=r'$\boldsymbol{n}$', offset=(-16, 0), lw=2.3)
for radius, lo, hi in [(.9, 0, phi), (1.35, phi, np.pi/2)]:
    t = np.linspace(lo, hi, 80)
    ax.plot(radius*np.cos(t), radius*np.sin(t), color=C.INK, lw=1)
label(ax, r'$\varphi$', (1.04, .28), (0, 0), fontsize=12)
label(ax, r'$\frac{\pi}{2}-\varphi$', (.81, 1.42), (0, 0), fontsize=12)
ax.plot([0, .2, .2], [.2, .2, 0], color=C.INK, lw=.9)
dot(ax, [0, 0], '$O$', offset=(-15, -15))
label(ax, '$L$', 4.5*s, (7, -2), fontsize=12)
label(ax, '平面上的投影', (2.8, 0), (0, -23), ha='center')
label(ax, '平面', (-1.25, 0), (0, -20), ha='center')
ax.set_xlim(-1.8, 4.6); ax.set_ylim(-1.1, 3.3)
assert np.isclose(s @ np.array([0, 1]), np.sin(phi))
save(fig, 'C19-n6')
