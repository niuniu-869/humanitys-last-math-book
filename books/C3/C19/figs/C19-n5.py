import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(13, 9)
ax.set_aspect('equal'); ax.axis('off')
t = np.array([np.cos(np.pi/12), np.sin(np.pi/12)])
n = np.array([-t[1], t[0]])
o = np.zeros(2); h = 3.2*t; p = h+2.3*n; q = 2.3*n
band = np.array([-1.2*t-.12*n, 4.3*t-.12*n, 4.3*t+.12*n, -1.2*t+.12*n])
ax.add_patch(plt.Polygon(band, color=C.LIGHT, alpha=.5))
ax.plot(*np.array([-1.2*t, 4.3*t]).T, color=C.GRAY, lw=.8)
ax.plot(*np.array([o, h]).T, color=C.INK, ls='--', lw=1.5)
ax.plot(*np.array([h, p]).T, color=C.INK, ls=':', lw=1.6)
ax.plot(*np.array([q, p]).T, color=C.GRAY, ls='--', lw=1)
arrow(ax, o, 3*n, color=C.INK, lw=1.8, text=r'$\boldsymbol{n}$', offset=(-10, 5))
ax.plot(*np.array([o, q]).T, color=C.INK, lw=4, solid_capstyle='butt')
arrow(ax, o, p, color=C.INK, lw=1.2)
for base in [h, o]:
    ax.plot(*np.array([base-.18*t, base-.18*t+.18*n, base+.18*n]).T, color=C.INK, lw=.8)
dot(ax, o, '$M_0$', offset=(-12, -18))
dot(ax, h, '$H$', offset=(7, -15))
ax.scatter(*p, s=34, facecolors=C.PAPER, edgecolors=C.INK, zorder=7)
label(ax, '$P_1$', p, (7, 4))
label(ax, '$d$', (h+p)/2, (12, 0), fontsize=12)
label(ax, '投影长 $d$', q/2, (-14, 0), ha='right')
label(ax, r'$\overrightarrow{M_0P_1}$', p*.52, (12, -8))
label(ax, '平面（侧视）', 3.6*t, (0, -42), ha='center')
ax.set_xlim(-1.9, 4.6); ax.set_ylim(-.8, 3.7)
assert np.isclose(t @ n, 0)
assert np.isclose(np.linalg.norm(p-h), abs(p @ n))
save(fig, 'C19-n5')
