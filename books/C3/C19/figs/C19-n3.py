import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label
from _geometry import setup, line, vector, text, axes, fill, bounds

fig, ax = setup(13, 12)
o = np.zeros(3); a = np.array([3., 0, 0]); b = np.array([1.5, 2., 0])
n = np.cross(a, b); foot = np.array([1.5, 0, 0])
fill(ax, [o, a, a+b, b])
line(ax, [o, a, a+b, b, o])
vector(ax, o, a); vector(ax, o, b); vector(ax, o, n, lw=2.7)
line(ax, [foot, b], ls='--', lw=1.6)
line(ax, [foot+[.2, 0, 0], foot+[.2, .2, 0], foot+[0, .2, 0]], lw=1)
line(ax, [[.3, 0, 0], [.3, 0, .3], [0, 0, .3]], lw=1)
axes(ax, [4.3, 3, 6.6])
text(ax, n, r'$\boldsymbol{a}\times\boldsymbol{b}$', (10, -4), fontsize=12)
text(ax, a, r'底 $\Vert\boldsymbol{a}\Vert$', (0, -28), ha='center')
text(ax, b, r'高 $\Vert\boldsymbol{b}\Vert\sin\theta$', (17, -15))
text(ax, a, r'$\boldsymbol{a}$', (6, 6))
text(ax, b, r'$\boldsymbol{b}$', (6, 6))
t = np.linspace(0, np.arctan2(2, 1.5), 40)
arc = np.column_stack((.75*np.cos(t), .75*np.sin(t), np.zeros_like(t)))
line(ax, arc, lw=1.1)
vector(ax, arc[-4], arc[-1], lw=1.1)
assert np.allclose(n, [0, 0, 6])
assert np.isclose(np.linalg.norm(a)*np.linalg.norm(b-foot), np.linalg.norm(n))
bounds(ax, [a+b, a, b, n, [4.3, 0, 0], [0, 3, 0], [0, 0, 6.6]], 1.1)
save(fig, 'C19-n3')
