import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(13, 10)
xi = np.sqrt(3)
left = np.linspace(0, xi, 301)
right = np.linspace(xi, 3, 301)
ax.fill_between(left, left**2, 3, facecolor=C.PAPER, edgecolor=C.INK, hatch='///', lw=0.5)
ax.fill_between(right, 3, right**2, facecolor=C.LIGHT, edgecolor=C.INK, lw=0.5)
x = np.linspace(0, 3, 501)
ax.plot(x, x**2, color=C.INK, ls='-', lw=2.1)
ax.plot([0, 0, 3, 3], [3, 0, 0, 3], color=C.INK, ls='-', lw=0.8)
ax.plot([0, 3], [3, 3], color=C.INK, ls='--', lw=1.7)
ax.plot([3, 3], [3, 9], color=C.INK, ls='-', lw=0.8)
ax.plot([xi, xi], [0, 3], color=C.INK, ls=':', lw=1)
dot(ax, (xi, 3))
label(ax, '面积相等', (0.64, 2.1), ha='center')
label(ax, '面积相等', (2.65, 4.4), ha='center')
label(ax, r'$\bar f=3$', (0.28, 3), offset=(0, 10))
label(ax, '$y=x^2$', (2.12, 7.6))
ax.set(xlim=(0, 3.3), ylim=(0, 9.5), xlabel='$x$', ylabel='$y$')
ax.set_xticks([0, xi, 3], ['$0$', r'$\xi=\sqrt{3}$', '$3$'])
ax.set_yticks([0, 3, 6, 9])
assert np.isclose(xi**2, 3)
missing = 3*xi - xi**3/3
extra = (3**3/3-3*3) - (xi**3/3-3*xi)
assert np.isclose(missing, extra) and np.isclose(missing, 2*np.sqrt(3))
assert 3**3/3 == 3*3 == 9
fig.subplots_adjust(left=0.11, right=0.97, bottom=0.16, top=0.95)
save(fig, "C9-n5")
