import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(13, 8)
t = np.linspace(0, 45, 400)
ax.plot(t, 200 * (1 - np.exp(-0.1 * t)), color=C.INK, lw=2.2)
ax.plot(t, 200 + 0 * t, color=C.INK, lw=1.1, ls="--")
ax.plot(t, -200 * np.exp(-0.1 * t), color=C.INK, lw=1.3, ls=":")
label(ax, r"$y(t)=200(1-e^{-0.1t})$（实线）", (18, 200 * (1 - np.exp(-1.8))), offset=(0, -26))
label(ax, "特解 200（稳态，虚线）", (1, 171), fontsize=9)
label(ax, r"齐次部分 $-200e^{-0.1t}$（点线）", (18, -200 * np.exp(-1.8)), offset=(4, -22))
T = np.log(2) / 0.1
ax.vlines(T, -210, 150, color=C.GRAY, lw=0.8, ls="-")
label(ax, r"$T\approx6.93$", (T, -205), offset=(4, 0))
dot(ax, (T, 100), size=26)
dot(ax, (T, -100), size=26)
label(ax, "100", (T, 100), offset=(-26, 4)); label(ax, "$-100$", (T, -100), offset=(-34, -12))
arrow(ax, (T, -100), (0, 200), color=C.GRAY, lw=1.0)
label(ax, "同一时刻：实线 = 虚线 + 点线\n一个半衰期：差距减半", (T, 0), offset=(10, 6), fontsize=8.5)
ax.set_xlim(0, 45); ax.set_ylim(-210, 220)
ax.set_xlabel("$t$（小时）"); ax.set_ylabel("药量（mg）")
assert np.isclose(200 * (1 - np.exp(-0.1 * T)), 100)
assert np.isclose(200 * (1 - np.exp(-0.1 * 4 * T)), 187.5)
save(fig, "C17-n3")
