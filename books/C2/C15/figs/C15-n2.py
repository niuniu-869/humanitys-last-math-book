import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(12, 7.5)
x = np.linspace(-7, 7, 1600)
ax.plot(x, np.sin(x), color=C.LIGHT, lw=4.0, ls="-")
ax.plot(x, x, color=C.INK, lw=1.2, ls=":")
ax.plot(x, x - x**3 / 6, color=C.INK, lw=1.4, ls="--")
ax.plot(x, x - x**3 / 6 + x**5 / 120, color=C.INK, lw=1.1, ls="-")
label(ax, r"$\sin x$", (-6.7, 1.15), offset=(0, 0), ha="left", va="center")
label(ax, "1 次", (-2.25, -2.25), offset=(-4, 9))
label(ax, "3 次", (-3.0, -3.0 + 3.0**3 / 6), offset=(-42, 4))
label(ax, "5 次", (2.25, 2.25 - 2.25**3 / 6 + 2.25**5 / 120), offset=(5, 5))
ax.set_xlim(-7, 7); ax.set_ylim(-2.5, 2.5)
ax.set_xticks([-2*np.pi, -np.pi, 0, np.pi, 2*np.pi])
ax.set_xticklabels([r"$-2\pi$", r"$-\pi$", "0", r"$\pi$", r"$2\pi$"])
ax.set_yticks([-2, -1, 0, 1, 2])
ax.set_xlabel("$x$"); ax.set_ylabel("$y$")
save(fig, "C15-n2")
