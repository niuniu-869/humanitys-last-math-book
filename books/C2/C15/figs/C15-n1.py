import sys; sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[4] / "tools"))
from figstyle import plt, np, C, new_fig, new_fig3d, save, arrow, dot, label

fig, ax = new_fig(12, 7.5)
x = np.linspace(-1.2, 0.95, 1200)
ax.plot(x, 1 / (1 - x), color=C.LIGHT, lw=4.0, ls="-")
ax.plot(x, sum(x**k for k in range(3)), color=C.INK, lw=1.3, ls=":")
ax.plot(x, sum(x**k for k in range(5)), color=C.INK, lw=1.4, ls="--")
ax.plot(x, sum(x**k for k in range(9)), color=C.INK, lw=1.1, ls="-")
ax.axvline(-1, color=C.INK, lw=0.9, ls=":")
ax.axvline(1, color=C.INK, lw=0.9, ls="--")
ax.text(-0.95, 6.6, "宽线：$\\frac{1}{1-x}$\n点线：前 3 项\n虚线：前 5 项\n细实线：前 9 项", fontsize=11, va="top", ha="left", linespacing=1.6)
label(ax, "$x=-1$", (-1, 8.8), offset=(8, 0), ha="left", va="center")
label(ax, "$x=1$", (1.0, 8.8), offset=(4, 0))
ax.set_xlim(-1.2, 1.02); ax.set_ylim(-0.5, 10.5)
ax.set_xticks([-1, -0.5, 0, 0.5, 0.9])
ax.set_yticks([0, 2, 4, 6, 8, 10])
ax.set_xlabel("$x$"); ax.set_ylabel("$y$")
save(fig, "C15-n1")
